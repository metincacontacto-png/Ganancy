const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');

const envContent = fs.readFileSync('.env', 'utf8');
const env = {};
envContent.split('\n').forEach(line => {
  const parts = line.split('=');
  if (parts.length >= 2) {
    env[parts[0].trim()] = parts.slice(1).join('=').trim();
  }
});

const supabase = createClient(env.VITE_SUPABASE_URL, env.VITE_SUPABASE_ANON_KEY);

async function run() {
  const { data, error } = await supabase.from('deudas').select('fecha_inicio').limit(1);
  if (error) {
    console.log("fecha_inicio column test failed:", error.code, error.message);
  } else {
    console.log("fecha_inicio column exists! Data:", data);
  }
}

run();
